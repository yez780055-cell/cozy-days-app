import { LunarYear, Lunar } from 'lunar-typescript';
import { writeFile } from 'node:fs/promises';

// Reproducible calendar data for the exact range supported by the date picker.
const rows = [];
for (let year = 1000; year <= 9998; year++) {
  const months = LunarYear.fromYear(year).getMonths().filter(month => month.getYear() === year);
  if (months.length < 12 || months.length > 13) throw new Error(`Invalid lunar year ${year}`);
  const data = Object.fromEntries(months.map(month => [month.getMonth(),
    [Lunar.fromYmd(year, month.getMonth(), 1).getSolar().toYmd(), month.getDayCount()]]));
  rows.push(`(${year},'${JSON.stringify(data)}'::jsonb)`);
}
const sql = `-- Generated by scripts/generate-lunar-sql.mjs from the locked lunar-typescript version.
-- Local/staging migration only: production execution requires separate authorization.
begin;
create table if not exists cozy_days_private.lunar_year (
  year integer primary key, months jsonb not null
);
alter table cozy_days_private.lunar_year enable row level security;
revoke all on cozy_days_private.lunar_year from public, anon, authenticated;
insert into cozy_days_private.lunar_year(year, months) values
${rows.join(',\n')}
on conflict (year) do update set months = excluded.months;

-- The library uses the Julian calendar before 1582-10-15 and skips the reform gap.
create or replace function cozy_days_private.civil_jdn(y integer, m integer, d integer)
returns integer language plpgsql immutable strict set search_path = pg_catalog as $$
declare a integer := (14-m)/12; yy integer := y+4800-a; mm integer := m+12*a-3;
begin
  if y=1582 and m=10 and d between 5 and 14 then return null; end if;
  if y*10000+m*100+d < 15821015 then
    return d+(153*mm+2)/5+365*yy+yy/4-32083;
  end if;
  return d+(153*mm+2)/5+365*yy+yy/4-yy/100+yy/400-32045;
end $$;

create or replace function cozy_days_private.valid_calendar(value jsonb)
returns boolean language plpgsql stable set search_path = pg_catalog as $$
declare lunar jsonb; entry jsonb; y integer; m integer; d integer; ny numeric; nm numeric; nd numeric; solar text; start_day text; item jsonb;
begin
  if value ? 'calendar' and (jsonb_typeof(value->'calendar') <> 'string'
      or value->>'calendar' not in ('solar','lunar')) then return false; end if;
  if value ? 'specialDays' then
    if jsonb_typeof(value->'specialDays') <> 'array' then return false; end if;
    if jsonb_array_length(value->'specialDays') > 100 then return false; end if;
    for item in select x from jsonb_array_elements(value->'specialDays') x loop
      if jsonb_typeof(item) <> 'number' then return false; end if;
      if (item::text)::numeric not between 1 and 1000000
         or (item::text)::numeric <> trunc((item::text)::numeric) then return false; end if;
    end loop;
  end if;
  if not value ? 'lunarDate' then return coalesce(value->>'calendar','solar') <> 'lunar'; end if;
  lunar := value->'lunarDate';
  if jsonb_typeof(lunar) <> 'object' then return false; end if;
  if jsonb_typeof(lunar->'year') is distinct from 'number' or jsonb_typeof(lunar->'month') is distinct from 'number'
    or jsonb_typeof(lunar->'day') is distinct from 'number' then return false; end if;
  ny := (lunar->>'year')::numeric; nm := (lunar->>'month')::numeric; nd := (lunar->>'day')::numeric;
  if ny not between 1000 and 9998 or abs(nm) not between 1 and 12 or nd not between 1 and 30
    or ny <> trunc(ny) or nm <> trunc(nm) or nd <> trunc(nd) then return false; end if;
  y := ny::integer; m := nm::integer; d := nd::integer;
  select months->m::text into entry from cozy_days_private.lunar_year where year=y;
  if entry is null or d > (entry->>1)::integer then return false; end if;
  solar := value->>'date'; start_day := entry->>0;
  return coalesce(cozy_days_private.civil_jdn(substring(solar,1,4)::integer,substring(solar,6,2)::integer,substring(solar,9,2)::integer)
    = cozy_days_private.civil_jdn(substring(start_day,1,4)::integer,substring(start_day,6,2)::integer,substring(start_day,9,2)::integer)+d-1, false);
exception when invalid_text_representation or numeric_value_out_of_range then return false;
end $$;

-- Keep the original contract for all other fields and preserve its error response.
do $$ begin
  if to_regprocedure('cozy_days_private.validate_record_legacy(text,text,jsonb)') is null then
    alter function cozy_days_private.validate_record(text,text,jsonb) rename to validate_record_legacy;
  end if;
end $$;
create or replace function cozy_days_private.validate_record(kind text, record_id text, value jsonb)
returns text language plpgsql stable set search_path = pg_catalog as $$
declare reason text;
begin
  reason := cozy_days_private.validate_record_legacy(kind, record_id, value);
  if reason is not null then return reason; end if;
  if kind = 'anniversary' and not cozy_days_private.valid_calendar(value) then return 'invalid'; end if;
  return null;
end $$;
revoke all on function cozy_days_private.valid_calendar(jsonb), cozy_days_private.civil_jdn(integer,integer,integer),
  cozy_days_private.validate_record(text,text,jsonb), cozy_days_private.validate_record_legacy(text,text,jsonb)
  from public, anon, authenticated;
commit;
`;
await writeFile(new URL('../cloudbase/003_lunar_validation.sql', import.meta.url), sql);

import { test, expect } from '@playwright/test';
test.use({ timezoneId:'Asia/Shanghai' });
test.beforeEach(async ({page})=>{
 await page.clock.setFixedTime(new Date('2026-11-19T12:00:00+08:00'));
 await page.route('http://cozy-days.test/**',async route=>{const path=new URL(route.request().url()).pathname;try{await route.fulfill({path:'dist'+(path==='/'?'/index.html':path)});}catch{await route.fulfill({status:404});}});
 await page.goto('http://cozy-days.test/');
});
for(const [width,height] of [[360,740],[393,852],[430,932]]) test('首页导航 '+width,async({page})=>{
 await page.setViewportSize({width,height});
 const nav=page.getByRole('navigation',{name:'应用模块'});
 const scene=page.locator('.home-scene');
 await expect(nav.getByRole('button')).toHaveCount(4);
 await expect(nav).toHaveCSS('height','66px');
 await expect(scene).toHaveCSS('height',width===360?'195px':'220px');
 await expect(scene).toHaveCSS('border-top-left-radius','52px');
 await expect(page.locator('.home-room')).toHaveCSS('object-position','50% 62%');
 await expect(page.locator('.home-stamp')).toHaveAttribute('datetime','2026-11-19');
 await expect(page.getByText('今天还没有待办')).toBeVisible();
 await page.getByRole('button',{name:'添加待办',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('textbox',{name:'想做些什么？'}).fill('首页测试');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await nav.getByRole('button',{name:'首页'}).click();
 await expect(page.getByText('已完成 0 / 1 件')).toBeVisible();
 await expect(page.getByRole('progressbar',{name:'今日待办进度'})).toHaveAttribute('max','1');
 await page.getByRole('button',{name:'打开应用设置'}).click();
 for (const group of ['外观','记录','数据']) await expect(page.getByRole('region',{name:group,exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:/数据备份与恢复/})).toBeVisible();
 await expect(nav.getByRole('button',{name:'首页'})).toHaveAttribute('aria-current','page');
 await page.getByRole('button',{name:'周期信息',exact:true}).click();
 await expect(page.getByRole('heading',{name:'周期信息'})).toBeVisible();
 await page.getByRole('button',{name:'返回设置',exact:true}).click();
 await page.getByRole('button',{name:'返回上一页',exact:true}).click();
 await page.getByRole('button',{name:'记录生理期',exact:true}).click();
 await expect(page.locator('.period-calendar')).toBeVisible();
 await expect(page.locator('.period-header')).toHaveCount(0);
 await nav.getByRole('button',{name:'纪念日'}).click();
 await expect(page.getByRole('region',{name:'纪念日收藏'})).toBeVisible();
 await expect(page.locator('.ann-hero')).toHaveCount(0);
 await nav.getByRole('button',{name:'首页'}).click();
 await page.getByRole('button',{name:'新增纪念日',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'新增纪念日'})).toBeVisible();
 await expect(page.locator('.phone')).toHaveJSProperty('clientWidth',width);
});

test('首页逾期入口保留跨日清单，最近纪念日入口进入收藏',async({page})=>{
 const nav=page.getByRole('navigation');
 await page.getByRole('button',{name:'添加待办',exact:true}).click();
 let dialog=page.getByRole('dialog');
 await dialog.getByRole('textbox',{name:'想做些什么？'}).fill('昨天的待办');
 await dialog.getByLabel('归属日期',{exact:true}).fill('2026-11-18');
 await dialog.getByRole('button',{name:'保存',exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await nav.getByRole('button',{name:'首页',exact:true}).click();
 await page.getByRole('button',{name:/还有 1 件过期待办/}).click();
 await expect(page.getByRole('button',{name:/^全部未完成/})).toHaveAttribute('aria-pressed','true');
 await expect(page.getByRole('button',{name:'编辑：昨天的待办'})).toBeVisible();
 await nav.getByRole('button',{name:'首页',exact:true}).click();
 await page.getByRole('button',{name:'新增纪念日',exact:true}).click();
 dialog=page.getByRole('dialog');
 await dialog.getByLabel('纪念日名称').fill('下一次纪念');
 await dialog.getByLabel('日期',{exact:true}).fill('2026-11-27');
 await dialog.getByRole('button',{name:'保存纪念日'}).click();
 await expect(dialog).toHaveCount(0);
 await nav.getByRole('button',{name:'首页',exact:true}).click();
 const event=page.getByRole('button',{name:/下一次纪念.*8 天后/});
 await expect(event.locator('time')).toHaveAttribute('datetime','2026-11-27');
 await event.click();
 await expect(page.getByRole('region',{name:'纪念日收藏'})).toBeVisible();
});
